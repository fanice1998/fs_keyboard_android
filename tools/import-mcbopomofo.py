#!/usr/bin/env python3
"""Convert McBopomofo's compiled data.txt into the keyboard's phrase table.

data.txt is produced by `make data.txt` in McBopomofo's Source/Data
(https://github.com/openvanilla/McBopomofo, MIT; phrases derived from libtabe, BSD).
Each data row is `reading text score`, syllables joined by `-`, score a log10 probability.

Output rows are `reading<TAB>text<TAB>score`, syllables joined by a space, sorted by
reading and then by descending score. Punctuation, symbols and date macros are dropped.

    python3 -I tools/import-mcbopomofo.py <data.txt> <commit> app/src/main/assets/lexicon/mcbopomofo.tsv
"""
import sys

BOPOMOFO = {chr(code) for code in range(0x3105, 0x312A)}
TONES = set("ˊˇˋ˙")


def syllable_ok(syllable):
    if not syllable:
        return False
    body = syllable[:-1] if syllable[-1] in TONES else syllable
    return bool(body) and all(ch in BOPOMOFO for ch in body)


def main(source, commit, target):
    best = {}
    with open(source, encoding="utf-8") as rows:
        for line in rows:
            if line.startswith(("#", "_")):
                continue
            parts = line.split()
            if len(parts) != 3:
                continue
            reading, text, score = parts
            if text.startswith("MACRO@"):
                continue
            syllables = reading.split("-")
            if not all(syllable_ok(s) for s in syllables):
                continue
            try:
                value = float(score)
            except ValueError:
                continue
            key = (" ".join(syllables), text)
            if key not in best or value > best[key]:
                best[key] = value

    ordered = sorted(best.items(), key=lambda item: (item[0][0], -item[1], item[0][1]))
    with open(target, "w", encoding="utf-8", newline="\n") as out:
        out.write(f"# McBopomofo {commit}, MIT License. Phrases derived from libtabe, BSD License.\n")
        out.write("# Generated by tools/import-mcbopomofo.py. reading<TAB>text<TAB>log10 probability.\n")
        for (reading, text), value in ordered:
            out.write(f"{reading}\t{text}\t{value:.4f}\n")
    print(f"{len(ordered)} rows -> {target}")


if __name__ == "__main__":
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    main(*sys.argv[1:])
